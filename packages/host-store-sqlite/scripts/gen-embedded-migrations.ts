#!/usr/bin/env bun
/**
 * Regenerate `src/embedded-migrations.ts` from `drizzle/**` (every `.sql` plus
 * `meta/*.json`, sorted by path) so the runtime always migrates from a
 * committed, in-repo map — no on-disk folder lookup (D9). Run after every
 * `drizzle-kit generate`; `tests/unit/embedded-migrations.test.ts` fails when
 * the two drift apart.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const PACKAGE_DIR = resolve(import.meta.dirname, "..");
const DRIZZLE_DIR = resolve(PACKAGE_DIR, "drizzle");
const OUT_FILE = resolve(PACKAGE_DIR, "src/embedded-migrations.ts");

/** `drizzle/**` as `<relative path> → content`, the shape the runtime map has. */
export function collectMigrationFiles(dir = DRIZZLE_DIR): Map<string, string> {
  const files = readdirSync(dir, { recursive: true, encoding: "utf8" })
    .filter(rel => rel.endsWith(".sql") || (rel.startsWith("meta/") && rel.endsWith(".json")))
    .sort();
  return new Map(files.map(rel => [rel, readFileSync(resolve(dir, rel), "utf8")]));
}

export function renderEmbeddedMigrations(files: ReadonlyMap<string, string>): string {
  const entries = [...files].map(([name, content]) => `  [${JSON.stringify(name)}, ${JSON.stringify(content)}],`);
  return [
    "// GENERATED by scripts/gen-embedded-migrations.ts from drizzle/** — do not edit.",
    "// Regenerate with `bun run gen:migrations` after every `drizzle-kit generate`;",
    "// tests/unit/embedded-migrations.test.ts fails while this file is out of sync.",
    "export const embeddedMigrations = new Map<string, string>([",
    ...entries,
    "]);",
    "",
  ].join("\n");
}

if (import.meta.main) {
  writeFileSync(OUT_FILE, renderEmbeddedMigrations(collectMigrationFiles()));
  // eslint-disable-next-line no-console
  console.log(`[gen:migrations] wrote ${OUT_FILE}`);
}
