#!/usr/bin/env bun
/* eslint-disable no-console */
/**
 * Generate the machine-checkable JSON Schema for the v2 frame catalog from the
 * zod source of truth (`src/protocol/frames.ts`) and embed it in
 * `docs/protocol.md` under the trailing section "## 8. Frame JSON Schema
 * (generated)".
 *
 * Idempotent: the section is delimited by a stable marker; re-running REPLACES
 * the block (never appends), so a second run leaves protocol.md byte-identical.
 * Only §8 is touched — §1–§7 prose/tables are never rewritten.
 *
 * Usage:  bun run gen:frames-schema     (alias of `bun run scripts/gen-frames-schema.ts`)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { AgentFrame, AnyFrame, HostFrame } from "@gino/host-core";
import { z } from "zod";

const PROTOCOL_MD = resolve(import.meta.dir, "../docs/protocol.md");
export const MARKER = "## 8. Frame JSON Schema (generated)";

/** Build the JSON Schema for the whole catalog plus per-direction sub-schemas. */
export function buildSchema(): unknown {
  const schema = z.toJSONSchema(AnyFrame, { target: "draft-2020-12" });
  return {
    title: "Gino host ⇄ agent protocol v2 — frame catalog",
    description:
      "Generated from src/protocol/frames.ts (zod). `AnyFrame` = a valid v2 frame in either "
      + "direction. Frames and `data` objects are open (additive-compatible): unknown fields are "
      + "accepted, unknown `type`s are rejected. See protocol.md §4–§6.",
    ...schema,
    $defs: {
      ...(typeof schema === "object" && schema !== null && "$defs" in schema
        ? (schema as { $defs?: Record<string, unknown> }).$defs
        : {}),
      AgentFrame: z.toJSONSchema(AgentFrame, { target: "draft-2020-12" }),
      HostFrame: z.toJSONSchema(HostFrame, { target: "draft-2020-12" }),
    },
  };
}

export function renderSection(): string {
  const json = JSON.stringify(buildSchema(), null, 2);
  return [
    MARKER,
    "",
    "<!-- GENERATED by scripts/gen-frames-schema.ts from src/protocol/frames.ts — DO NOT EDIT.",
    "     Regenerate with `bun run gen:frames-schema`. -->",
    "",
    "The machine-checkable JSON Schema for the v2 frame catalog (§5), exported from the single",
    "zod source of truth in [`src/protocol/frames.ts`](../src/protocol/frames.ts). `AnyFrame` is",
    "the union of the agent→host (`AgentFrame`) and host→agent (`HostFrame`) catalogs; both are",
    "also exposed under `$defs`. Frames and their `data` objects are **open** — additive fields",
    "validate (protocol §1/§4.2) — while an unknown `type` matches no member and is rejected.",
    "",
    "```json",
    json,
    "```",
  ].join("\n");
}

function main(): void {
  const md = readFileSync(PROTOCOL_MD, "utf8");
  const markerIdx = md.indexOf(`\n${MARKER}`);
  const base = (markerIdx === -1 ? md : md.slice(0, markerIdx)).replace(/\s*$/, "");
  const next = `${base}\n\n${renderSection()}\n`;

  if (next === md) {
    console.log("docs/protocol.md §8 already up to date — no change.");
    return;
  }
  writeFileSync(PROTOCOL_MD, next);
  console.log(`Wrote docs/protocol.md §8 (${next.length - base.length} bytes generated).`);
}

// Only mutate the doc when invoked directly; importing (e.g. the contract test's
// drift guard) just pulls `buildSchema`/`renderSection` with no side effect.
if (import.meta.main) {
  main();
}
